import { chromium } from 'playwright-core'
const EXE = 'C:/Users/HUAWEI/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe'
const browser = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 860 } })
const logs = []
page.on('console', m => { if (m.type()==='error') logs.push(m.text()) })
page.on('pageerror', e => logs.push('PAGEERROR '+e.message))
await page.goto('http://127.0.0.1:8123/?open=1', { waitUntil: 'networkidle' })
const R = {}
R.calcBtn = await page.locator('button[aria-label="计算器"]').count()
await page.locator('button[aria-label="计算器"]').click()
await page.waitForSelector('.calc-grid')
R.keys = await page.locator('.calc-key').count()
const key = (l)=>page.getByRole('button',{name:l,exact:true}).click()
const cur = ()=>page.locator('.calc-current').innerText().then(s=>s.trim())
for (const k of ['2','+','3','=']) await key(k); R.add = await cur()
for (const k of ['2','0','0','+','1','0','%','=']) await key(k); R.pct = await cur()
for (const k of ['(','1','+','2',')','×','3','=']) await key(k); R.paren = await cur()
// 换算 -> 长度
await page.getByRole('button',{name:'换算',exact:true}).click()
await page.waitForSelector('.cal-unit')
await page.locator('.cal-sub-6 button',{hasText:'长度'}).first().click()
await page.waitForTimeout(100)
await page.locator('.cal-convert-line select').first().selectOption({label:'米 (m)'})
await page.locator('.cal-convert-line select').nth(1).selectOption({label:'英尺 (ft)'})
await page.locator('.cal-row input').first().fill('1')
await page.waitForTimeout(150)
R.mToFt = await page.locator('.cal-result strong').innerText().then(s=>s.trim())
// 温度 100C -> F
await page.locator('.cal-sub-6 button',{hasText:'温度'}).first().click()
await page.waitForTimeout(100)
await page.locator('.cal-row input').first().fill('100')
await page.waitForTimeout(120)
R.c100 = await page.locator('.cal-result strong').innerText().then(s=>s.trim())
// 货币 1 CNY -> USD (离线估算)
await page.locator('.cal-sub-6 button',{hasText:'货币'}).first().click()
await page.waitForTimeout(300)
R.cnyUsd = await page.locator('.cal-result strong').innerText().then(s=>s.trim())
// 日期 -> 日期差 与 年龄
await page.getByRole('button',{name:'日期',exact:true}).click()
await page.waitForSelector('.cal-date')
await page.locator('.cal-sub button',{hasText:'日期差'}).first().click()
R.dateDiff = (await page.locator('.cal-result').innerText()).replace(/\s+/g,' ').slice(0,24)
await page.locator('.cal-sub button',{hasText:'年龄'}).first().click()
R.age = (await page.locator('.cal-result').innerText()).replace(/\s+/g,' ').slice(0,40)
await browser.close()
console.log(JSON.stringify(R,null,2))
console.log('ERRORS:', logs.length?logs.join(' | '):'none')
